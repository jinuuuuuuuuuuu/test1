"""검색 질의 재작성 — 사용자의 일상어를 문서의 제도 용어로 옮긴다.

## 왜 필요한가

RAG 검색은 사용자 질문을 **그대로** 임베딩해 문서와 대조한다. 그런데 사용자는
제도 용어를 모른 채 대화체로 묻고, 문서는 제도 용어로 쓰여 있다. 두 표현이
의미상 같아도 임베딩 공간에서는 멀어서, 엉뚱한 문서가 잡히고 LLM이 그 빈틈을
학습 지식으로 메운다 — 할루시네이션의 최대 발생원이다.

실측(2026-09-03, 10문항 스팟체크 S03):
    질문: "전업주부인데 노후 대비하고 싶어서 뭐라도 시작하려구요. 뭐가 좋을까요?"
    원문 검색  -> d=31.80  "연금실제수령연차 전략", "MP 알림톡 FAQ"  (완전 무관)
    결과: LLM이 연금저축 세액공제 한도를 400만원(폐지된 값), 세율을 3.3~5.5%로 창작
    재작성 후 -> d=13.16  "연금계좌 종류와 가입대상", "연금저축·IRP 납입한도와 세액공제한도"
                          (= 창작된 그 내용의 정답 문서)

같은 개선이 다른 실패에서도 재현됐다:
    "65세 정년 은퇴... 절세 방법"      22.55 -> 14.52 (이연퇴직소득세 감면 문서 확보)
    "친구가 IRP 있는데 만기가..."       22.12 -> 13.16

## 왜 거리 임계값 조정으로는 안 되는가

먼저 그 길을 시도했고, 데이터가 불가능하다고 말했다. 정상 질의의 최소거리를
10건 측정하니 12.79~36.88로 퍼져 있었고, S03의 쓰레기 결과(31.80~33.53)와
**구간이 겹친다**. 예를 들어 "DB형과 DC형 차이"의 d=34.30은 DB형 정의를 정확히
담은 올바른 문서다. 임계값을 낮추면 이런 정상 검색이 먼저 죽는다.

즉 문제는 "얼마나 먼가"가 아니라 "무엇으로 찾는가"였다.

## 설계 원칙 (실측으로 정한 것)

1. **원문 검색을 버리지 않고 더한다.** 이미 제도 용어로 잘 물은 질문은 재작성이
   오히려 나빠진다(실측: "연금 실제수령연차랑 연금수령연차가 같은 말 아닌가요?"
   10.65 -> 17.32). 원문 결과와 재작성 결과를 합쳐 거리순으로 고른다.

2. **범위 밖 질문을 되살리지 않는다.** 재작성기는 무엇을 주든 연금 검색어를
   만들어낸다 — "오늘 점심 뭐 먹지"가 재작성 후 5건을 반환했다(원문은 0건).
   원문 검색이 0건이면 그 질문은 보유 문서로 답할 수 없다는 뜻이므로, 재작성
   결과도 쓰지 않는다. 이 규칙이 "빈 리스트 = 한계 고지" 계약을 지킨다.

3. **실패해도 원문 결과로 진행한다.** 재작성은 LLM 호출이라 느리거나 실패할 수
   있다. 어떤 예외도 검색 자체를 막지 않는다.
"""

from __future__ import annotations

QUERY_REWRITE_MODEL = "HCX-005"

_REWRITE_SYSTEM_PROMPT = """당신은 연금 문서 검색용 질의 생성기입니다. 답변을 쓰지 말고,
검색어만 만드세요.

사용자 질문을 보고 연금 제도·세제 문서에서 답을 찾기 위한 검색어를 2~3개 만드세요.
핵심은 사용자가 쓴 **일상 표현을 제도 용어로 바꾸는 것**입니다 — 문서는 제도 용어로
쓰여 있어서, 일상어를 그대로 검색하면 엉뚱한 문서가 잡힙니다.

예시:
- "전업주부인데 노후 대비하고 싶어요" -> 연금저축 가입대상 소득 없는 경우 / 연금저축 세액공제
- "정년 은퇴 앞두고 절세하고 싶어" -> 퇴직금 연금수령 이연퇴직소득세 감면 / 연금계좌 세액공제
- "친구가 IRP 만기를 궁금해해" -> IRP 연금수령 요건과 개시 시기
- "중간에 빼서 쓸 수 있나요" -> 퇴직연금 중도인출 사유와 요건

규칙:
- 검색어만 한 줄에 하나씩 출력하고 설명·번호·기호를 붙이지 마세요.
- 질문에 없는 조건(나이·금액 등)을 지어내지 마세요.
- 연금과 무관한 질문이면 아무것도 출력하지 마세요."""

_MAX_QUERIES = 3
_MAX_QUERY_LEN = 80


def _parse_queries(raw: str) -> list[str]:
    """모델 출력에서 검색어만 추린다.

    ⚠️ "한 줄에 하나씩"이라고 지시해도 모델이 " / "나 ", "로 이어 붙여 한 줄에
    내놓는 일이 잦다(실측). 그대로 두면 검색어 3개가 한 덩어리로 임베딩돼 재작성
    효과가 크게 줄어든다 — 실측 S03에서 분리 전 d=23.77, 분리 후 d=13.16.
    줄바꿈뿐 아니라 구분자로도 나눈다.
    """
    import re

    queries: list[str] = []
    for line in (raw or "").splitlines():
        for piece in re.split(r"\s*/\s*|\s*,\s*|\s*;\s*", line):
            cleaned = piece.strip().strip("-*·•").strip()
            # "1. ", "2) " 같은 번호 접두사 제거
            while cleaned[:1].isdigit():
                cleaned = cleaned[1:].lstrip(")., ").strip()
            if not cleaned or len(cleaned) > _MAX_QUERY_LEN:
                continue
            if cleaned not in queries:
                queries.append(cleaned)
            if len(queries) >= _MAX_QUERIES:
                return queries
    return queries


def rewrite_search_queries(question: str) -> list[str]:
    """질문을 제도 용어 검색어 2~3개로 바꾼다. 실패하면 빈 리스트.

    호출측은 이 결과를 **원문 검색에 더해서** 쓴다 — 대체하지 않는다.
    """
    if not (question or "").strip():
        return []
    try:
        from src.agents.llm import get_llm, invoke_with_retry

        llm = get_llm(QUERY_REWRITE_MODEL)
        response = invoke_with_retry(
            llm,
            [
                {"role": "system", "content": _REWRITE_SYSTEM_PROMPT},
                {"role": "user", "content": question},
            ],
        )
        return _parse_queries(getattr(response, "content", "") or "")
    except Exception:
        # 재작성은 품질 향상 수단일 뿐이라, 실패해도 원문 검색으로 진행해야 한다.
        return []
