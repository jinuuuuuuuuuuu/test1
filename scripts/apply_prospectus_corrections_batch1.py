wb = openpyxl.load_workbook(PATH, keep_vba=True)
ws = wb["투자설명서_파싱"]

# 컬럼(0-indexed): 2=상품코드, 11=판매클래스, 28=매입기준, 29=환매기준, 30=환매대금지급,
# 31=환매수수료, 32=과세특징, 34=최초설정일, 36=검수메모, 37=검수상태

def find_rows(code):
    rows = []
    for row in ws.iter_rows(min_row=6):
        if row[2].value == code:
            rows.append(row)
    return rows


def find_row_by_class(code, cls):
    for row in ws.iter_rows(min_row=6):
        if row[2].value == code and row[11].value == cls:
            return row
    raise ValueError(f"{code}/{cls} not found")


def fill_common(row, 매입, 환매, 지급, 수수료, 과세, note_suffix=""):
    if row[28].value in (None, "NULL", ""):
        row[28].value = 매입
    if row[29].value in (None, "NULL", ""):
        row[29].value = 환매
    if row[30].value in (None, "NULL", ""):
        row[30].value = 지급
    if row[31].value in (None, "NULL", ""):
        row[31].value = 수수료
    if row[32].value in (None, "NULL", ""):
        row[32].value = 과세
    old_note = row[36].value or ""
    row[36].value = (old_note + " " + note_suffix).strip() if note_suffix else old_note
    row[37].value = "검수완료"


