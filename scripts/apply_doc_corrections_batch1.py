def find_row(chunk_id):
    for row in ws.iter_rows(min_row=6):
        if row[7].value == chunk_id:  # col H = chunk_id (0-indexed 7)
            return row
    raise ValueError(f"chunk_id not found: {chunk_id}")


def set_status(chunk_id, status):
    row = find_row(chunk_id)
    row[12].value = status  # col M = 검수상태


def append_chunk(file_num, file_title, file_format, category, section, location, chunk_id,
                  chunk_text, has_table, table_text, note, status):
    ws.append([file_num, file_title, file_format, category, "RAG", section, location,
               chunk_id, chunk_text, has_table, table_text, note, status])


