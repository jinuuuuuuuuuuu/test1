wb = openpyxl.load_workbook(PATH, keep_vba=True)
ws = wb["파싱 결과"]


def find_row(chunk_id):
    for row in ws.iter_rows(min_row=6):
        if row[7].value == chunk_id:
            return row
    raise ValueError(chunk_id)


def set_both(chunk_id, new_chunk_text, new_structured, note):
    r = find_row(chunk_id)
    r[8].value = new_chunk_text
    r[10].value = new_structured
    r[11].value = ((r[11].value or "") + " " + note).strip()
    r[12].value = "검수완료(수정)"


